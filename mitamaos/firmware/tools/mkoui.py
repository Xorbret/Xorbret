"""Generate src/detect/oui_table.h from the IEEE MA-L registry.

Usage: python3 tools/mkoui.py oui.txt > src/detect/oui_table.h
(oui.txt: https://standards-oui.ieee.org/oui/oui.txt)

Only blocks whose IEEE registrant is the named company are included, so
every row is a fact you can look up. Grades follow outline §5: High = the
block belongs to the company that makes the product; Medium = a vendor
whose range covers much more than the product; Low = module/ODM vendors.
Bare Espressif and other generic silicon are deliberately excluded: every
ESP32 project (MitamaOS included) would flag every other one.
"""
import re, sys

# exact IEEE organisation name (case-insensitive) -> (type, grade, label)
VENDORS = {
    "flock safety":                            ("FLOCK",   "HIGH", "Flock Safety"),
    "axon enterprise, inc.":                   ("AXON",    "HIGH", "Axon"),
    "watchguard video":                        ("AXON",    "MED",  "WatchGuard body cam"),
    "digital ally, inc.":                      ("AXON",    "MED",  "Digital Ally body cam"),
    "shotspotter, inc.":                       ("RAVEN",   "HIGH", "ShotSpotter"),
    "motorola solutions inc.":                 ("ALPR",    "MED",  "Motorola Solutions"),
    "motorola solutions malaysia sdn. bhd.":   ("ALPR",    "MED",  "Motorola Solutions"),
    "genetec inc.":                            ("ALPR",    "MED",  "Genetec"),
    "ring llc":                                ("RING",    "HIGH", "Ring"),
    "wyze labs inc":                           ("CAMERA",  "HIGH", "Wyze"),
    "hangzhou hikvision digital technology co.,ltd.": ("CAMERA", "HIGH", "Hikvision"),
    "verkada inc":                             ("CAMERA",  "HIGH", "Verkada"),
    "avigilon alta":                           ("CAMERA",  "HIGH", "Avigilon"),
    "axis communications ab":                  ("CAMERA",  "HIGH", "Axis"),
    "i-pro co., ltd.":                         ("CAMERA",  "HIGH", "i-PRO"),
    "skydio inc.":                             ("DRONE",   "HIGH", "Skydio"),
    "sz dji technology co.,ltd":               ("DRONE",   "MED",  "DJI"),
    "parrot sa":                               ("DRONE",   "MED",  "Parrot"),
    "luxottica group s.p.a.":                  ("META",    "MED",  "Luxottica"),
    "shenzhen bolutek technology co.,ltd.":    ("SKIMMER", "LOW",  "HC-05 module"),
}

rows = []
for line in open(sys.argv[1], encoding="utf-8", errors="replace"):
    m = re.match(r"^([0-9A-F]{2})-([0-9A-F]{2})-([0-9A-F]{2})\s+\(hex\)\s+(.*\S)\s*$", line)
    if not m:
        continue
    org = m.group(4).strip().lower()
    if org in VENDORS:
        oui = int(m.group(1) + m.group(2) + m.group(3), 16)
        rows.append((oui,) + VENDORS[org])
rows.sort()
labels = sorted({r[3] for r in rows})

print("// Generated by tools/mkoui.py from the IEEE MA-L registry. Do not edit.")
print("// Every row's block is registered to the company named in its label.")
print("#pragma once")
print("#include <stdint.h>")
print("")
print("namespace Sig {")
print("static const char* const OUI_LABELS[] = {")
for l in labels:
    print(f'    "{l}",')
print("};")
print("struct OuiRow { uint32_t oui; uint8_t type; uint8_t grade; uint8_t label; };")
print("static const OuiRow OUI_TABLE[] = {   // sorted by oui for binary search")
for oui, t, g, l in rows:
    print(f"    {{ 0x{oui:06X}, T_{t}, G_{g}, {labels.index(l)} }},")
print("};")
print("static const int OUI_COUNT = sizeof(OUI_TABLE) / sizeof(OUI_TABLE[0]);")
print("}")
