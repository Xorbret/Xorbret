"""Generate src/net/ca_bundle.h: the Mozilla root CA list in ESP-IDF's
certificate-bundle format, for WiFiClientSecure::setCACertBundle().

Usage: python3 tools/mkcabundle.py /usr/share/ca-certificates/mozilla > src/net/ca_bundle.h

Format (ESP-IDF 4.4 gen_crt_bundle.py): u16 count, then per certificate,
sorted by DER subject: u16 subject length, u16 key length, DER subject,
DER SubjectPublicKeyInfo. All big-endian. Only names and keys are kept,
so verification needs very little RAM.
"""
import os, struct, sys
from cryptography import x509
from cryptography.hazmat.primitives import serialization

certs = []
src = sys.argv[1]
for name in sorted(os.listdir(src)):
    if not name.endswith(".crt"):
        continue
    data = open(os.path.join(src, name), "rb").read()
    for c in x509.load_pem_x509_certificates(data):
        certs.append(c)

certs.sort(key=lambda c: c.subject.public_bytes())
blob = struct.pack(">H", len(certs))
for c in certs:
    sub = c.subject.public_bytes()
    key = c.public_key().public_bytes(serialization.Encoding.DER,
                                      serialization.PublicFormat.SubjectPublicKeyInfo)
    blob += struct.pack(">HH", len(sub), len(key)) + sub + key

print("// Generated by tools/mkcabundle.py from the Mozilla root CA list. Do not edit.")
print(f"// {len(certs)} certificates, {len(blob)} bytes.")
print("#pragma once")
print("#include <stdint.h>")
print("#include <pgmspace.h>")
print("static const uint8_t CA_BUNDLE[] PROGMEM = {")
for i in range(0, len(blob), 20):
    print("    " + ", ".join(f"0x{b:02x}" for b in blob[i:i + 20]) + ",")
print("};")
